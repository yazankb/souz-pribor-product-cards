def build_user_prompt(product: ProductInput, report: SpecsReport) -> str:
    data = product.model_dump(exclude_none=True)
    missing = [m.field for m in report.missing]
    missing_text = ", ".join(missing) if missing else "нет"
    return (
        f"Тип прибора (определён автоматически): {report.profile.title}.\n"
        f"Отсутствуют во входных данных (не упоминай их значения): {missing_text}.\n\n"
        f"<product_data>\n{json.dumps(data, ensure_ascii=False, indent=2)}\n</product_data>\n\n"
        "Подготовь черновик карточки по правилам. Верни только JSON."
    )


def build_repair_prompt(issues: list[ValidationIssue], parse_error: str | None = None) -> str:
    lines = ["Автоматическая проверка нашла проблемы в твоём ответе:"]
    if parse_error:
        lines.append(f"- Ответ не соответствует JSON-схеме: {parse_error}")
    for issue in issues:
        lines.append(f"- {issue.field}: {issue.message}")
    lines += [
        "",
        "Исправь ТОЛЬКО перечисленное и верни полный JSON целиком по той же схеме.",
        "- Если число или термин отсутствует во входных данных — удали его или перефразируй без него.",
        f"- Если SEO description короче {SEO_DESCRIPTION_MIN} символов — расширь его за счёт назначения, "
        "применения и пользы для покупателя, НЕ добавляя новых технических фактов.",
        f"- Если длиннее {SEO_DESCRIPTION_MAX} — сократи. Если SEO title длиннее {SEO_TITLE_MAX} — сократи.",
    ]
    return "\n".join(lines)
